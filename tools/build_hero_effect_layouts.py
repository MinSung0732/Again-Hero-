"""Bake the exact shared symmetric effect crop; no runtime GPU readback."""
from pathlib import Path
from PIL import Image
import json, math, sys
repo = Path(__file__).resolve().parents[1]
root = repo/'assets/art/effects/hero_weapon_v2'
rows = []
for folder in sorted(root.iterdir()):
    manifest = json.loads((folder/'manifest.json').read_text())
    extent = 0
    dimensions = None
    frames = manifest['animation']['frames']
    for frame in frames:
        with Image.open(folder/frame) as image:
            image = image.convert('RGBA')
            if dimensions is None: dimensions = image.size
            assert dimensions == image.size == (128,128)
            box = image.getchannel('A').getbbox()
            if box: extent = max(extent, *(abs(v-64) for v in box))
    extent = min(math.ceil(extent)+2,64)
    assert extent > 2 and len(frames) == 8
    assert frames == [f'frames/effect_{i:02d}.png' for i in range(1,9)]
    directory = 'res://'+(folder/'frames').relative_to(repo).as_posix()
    rows.append(f'\t"{directory}": Rect2({64-extent}, {64-extent}, {extent*2}, {extent*2}),')
output = repo/'src/data/hero_effect_layout_catalog.gd'
content = 'extends RefCounted\n# Generated by tools/build_hero_effect_layouts.py from all eight alpha bounds.\n# Original center (64,64), shared dimensions and two-pixel margin are preserved.\nconst FRAME_COUNT := 8\nconst REGIONS := {\n'+'\n'.join(rows)+'\n}\n'
if '--check' in sys.argv:
    assert output.read_text() == content, 'Stale effect layouts; regenerate after changing frames'
else:
    output.write_text(content)
print('Baked effect layouts:', len(rows))
