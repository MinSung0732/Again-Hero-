"""Bake legacy weapon frame filenames from tracked assets, without opening PNGs."""
from pathlib import Path
import re, subprocess, sys
repo = Path(__file__).resolve().parents[1]
directories = sorted(set(re.findall(r'"effect_dir"\s*:\s*"([^"]+)"',(repo/'src/data/hero_weapon_catalog.gd').read_text())))
known = set(re.findall(r'"(res://[^"]+)":',(repo/'src/data/hero_effect_layout_catalog.gd').read_text()))
lines = []
for directory in directories:
    if directory in known: continue
    tracked = subprocess.check_output(['git','ls-tree','-r','--name-only','HEAD','--',directory.removeprefix('res://')],cwd=repo,text=True).splitlines()
    names = sorted(Path(path).name for path in tracked if path.endswith('.png') and str(Path(path).parent) == directory.removeprefix('res://'))
    assert names, directory
    lines.append('\t"'+directory+'": PackedStringArray(['+', '.join('"'+name+'"' for name in names)+']),')
content = '''extends RefCounted
# Generated by tools/build_hero_effect_frames.py; no exported directory scans.
const LAYOUTS := preload("res://src/data/hero_effect_layout_catalog.gd")
const LEGACY := {
'''+ '\n'.join(lines)+'''
}
static func files(directory: String) -> PackedStringArray:
	if LEGACY.has(directory): return LEGACY[directory]
	var names := PackedStringArray()
	if LAYOUTS.REGIONS.has(directory):
		for index in range(1,LAYOUTS.FRAME_COUNT+1): names.append("effect_%02d.png" % index)
	return names
'''
p = repo/'src/data/hero_effect_frame_catalog.gd'
if '--check' in sys.argv: assert p.read_text() == content, 'Regenerate weapon effect filenames'
else: p.write_text(content)
print('Legacy effect directories:',len(lines),'total directories:',len(directories))
